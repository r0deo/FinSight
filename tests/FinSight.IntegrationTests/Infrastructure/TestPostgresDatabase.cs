using Npgsql;
using Testcontainers.PostgreSql;

namespace FinSight.IntegrationTests.Infrastructure;

// Docker remains the default. The opt-in native runner supplies a disposable,
// loopback-only cluster; each fixture creates and owns a separate database.
public sealed class TestPostgresDatabase : IAsyncDisposable
{
    private readonly string? admin = Environment.GetEnvironmentVariable("FINSIGHT_TEST_POSTGRES_ADMIN");
    private PostgreSqlContainer? container;
    private string? connection;
    private readonly string database = "finsight_test_" + Guid.NewGuid().ToString("N");

    public string GetConnectionString() => connection ?? throw new InvalidOperationException("Test database has not started.");

    public async Task StartAsync()
    {
        if (string.IsNullOrWhiteSpace(admin))
        {
            container = new PostgreSqlBuilder("postgres:17-alpine").Build();
            await container.StartAsync();
            connection = container.GetConnectionString();
            return;
        }
        var settings = new NpgsqlConnectionStringBuilder(admin);
        if (settings.Host != "127.0.0.1" || settings.Database != "postgres" || settings.Port == 5432)
            throw new InvalidOperationException("Native tests require a dedicated loopback cluster on a non-default port.");
        await using var db = new NpgsqlConnection(admin);
        await db.OpenAsync();
        await using var command = new NpgsqlCommand($"CREATE DATABASE \"{database}\"", db);
        await command.ExecuteNonQueryAsync();
        settings.Database = database;
        connection = settings.ConnectionString;
    }

    public async ValueTask DisposeAsync()
    {
        if (container is not null) { await container.DisposeAsync(); return; }
        if (connection is null) return;
        using (var pool = new NpgsqlConnection(connection)) NpgsqlConnection.ClearPool(pool);
        await using var db = new NpgsqlConnection(admin);
        await db.OpenAsync();
        // This name is generated by this fixture, never supplied by configuration.
        await using var command = new NpgsqlCommand($"DROP DATABASE \"{database}\" WITH (FORCE)", db);
        await command.ExecuteNonQueryAsync();
    }
}
